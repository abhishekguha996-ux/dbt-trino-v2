"""Authentication and TLS against the lab's HTTPS listener (password file + JWT), and
profile validation.

Modeled on dbt-trino v1 profile methods none/ldap/jwt and the `cert` option. Uses throwaway
credentials generated by scripts/stack.py; nothing here is a real secret.
"""

import sys
import unittest
from pathlib import Path

from harness import TrinoTestCase, run_sql

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import stack  # noqa: E402

CA = str(stack.GEN / "ca.crt")
LDAP_USER, LDAP_PASSWORD = "dbt_ldap", stack.USERS["dbt_ldap"]
SPECIAL_USER, SPECIAL_PASSWORD = "special", stack.USERS["special"]
MODEL = {"models/m.sql": "{{ config(materialized='view') }} select 1 as id"}


def dbt_log(p) -> str:
    log = p.dir / "logs" / "dbt.log"
    return log.read_text() if log.exists() else ""


class TestAuthentication(TrinoTestCase):
    def https_project(self, files=MODEL, **profile):
        base = {"port": 8443, "roles": None}
        base.update(profile)
        return self.project("memory", files, profile_overrides=base)

    def test_ldap_with_ca_bundle(self):
        p = self.https_project(method="ldap", user=LDAP_USER, password=LDAP_PASSWORD, cert=CA)
        self.assertIn("All checks passed", p.dbt("debug").output)
        p.dbt("run")
        self.assertEqual(p.type_of("m"), "view")

    def test_wrong_password_is_rejected_and_redacted(self):
        secret = "definitely-wrong-password-0451"
        p = self.https_project(method="ldap", user=LDAP_USER, password=secret, cert=CA)
        result = p.dbt("debug", expect=False)
        self.assertNotIn(secret, result.output)
        self.assertNotIn(secret, dbt_log(p))
        self.assertRegex(result.output.lower(), r"401|unauthorized|authentication|invalid credentials")

    def test_password_with_url_special_characters(self):
        p = self.https_project({"models/who.sql": "{{ config(materialized='table') }} select current_user as u"},
                               method="ldap", user=SPECIAL_USER, password=SPECIAL_PASSWORD, cert=CA)
        self.assertIn("All checks passed", p.dbt("debug").output)
        result = p.dbt("run")
        self.assertEqual(p.rows("who"), [[SPECIAL_USER]])
        self.assertNotIn(SPECIAL_PASSWORD, result.output)
        self.assertNotIn(SPECIAL_PASSWORD, dbt_log(p))

    def test_jwt(self):
        token = stack.jwt("admin")
        p = self.https_project(method="jwt", user="admin", jwt_token=token, cert=CA)
        debug = p.dbt("debug")
        self.assertIn("All checks passed", debug.output)
        run = p.dbt("run")
        for output in (debug.output, run.output, dbt_log(p)):
            self.assertNotIn(token, output)

    def test_cert_false_skips_verification(self):
        p = self.https_project(method="ldap", user=LDAP_USER, password=LDAP_PASSWORD, cert=False)
        self.assertIn("All checks passed", p.dbt("debug").output)

    def test_untrusted_certificate_is_rejected(self):
        p = self.https_project(method="ldap", user=LDAP_USER, password=LDAP_PASSWORD)
        result = p.dbt("debug", expect=False)
        self.assertRegex(result.output.lower(), r"certificate|x509|tls")

    def test_password_over_http_is_rejected_before_connecting(self):
        p = self.https_project(method="ldap", user=LDAP_USER, password=LDAP_PASSWORD,
                               http_scheme="http", port=8080)
        result = p.dbt("debug", expect=False)
        self.assertIn("requires http_scheme: https", result.output)
        self.assertNotIn(LDAP_PASSWORD, result.output)

    def test_source_header_and_client_tags(self):
        p = self.project("memory", {"models/marker.sql": "select 'source-marker-7731' as m"},
                         profile_overrides={"client_tags": ["etl", "nightly"]})
        p.dbt("run")
        rows = run_sql(
            "select source from system.runtime.queries "
            "where query like '%source-marker-7731%' and query not like '%system.runtime%'")
        self.assertTrue(rows, "query not found in system.runtime.queries")
        self.assertTrue(all(r[0].startswith("dbt-trino-") for r in rows), rows)


class TestProfileValidation(TrinoTestCase):
    """Profile values that dbt-trino v1 ignores or misreads fail with a clear message."""

    def debug_output(self, **profile) -> str:
        p = self.project("memory", MODEL, profile_overrides=profile)
        return p.dbt("debug", expect=False).output

    def test_host_must_be_a_host_name(self):
        for host in ("localhost:9999", "https://localhost", "localhost/trino"):
            with self.subTest(host=host):
                self.assertIn(
                    "Trino 'host' must be a host name only, for example trino.example.com. Put the port "
                    f"in 'port' and the scheme in 'http_scheme'. Got: '{host}'",
                    self.debug_output(host=host))

    def test_query_timeout_accepts_seconds_and_durations(self):
        for value in (300, "300", "5m"):
            with self.subTest(query_timeout=value):
                p = self.project("memory", MODEL, profile_overrides={"query_timeout": value})
                p.dbt("run")
                self.assertEqual(p.type_of("m"), "view")

    def test_query_timeout_rejects_other_values(self):
        self.assertIn(
            "Trino 'query_timeout' must be a number of seconds or a duration such as 300s, 30m or 1h; "
            "got '5 minutes'",
            self.debug_output(query_timeout="5 minutes"))

    def test_starburst_url_is_rejected(self):
        secret = "starburst-lab-secret-6620"
        p = self.project("memory", MODEL, profile_overrides={
            "starburst_url": "https://starburst.example.invalid",
            "starburst_client_id": "lab-client",
            "starburst_secret_key": secret,
        })
        result = p.dbt("debug", expect=False)
        self.assertIn("Starburst Data Discovery sync (starburst_url) is not supported by the dbt v2 Trino "
                      "adapter. Remove the starburst_* keys from the profile.", result.output)
        self.assertNotIn(secret, result.output)
        self.assertNotIn(secret, dbt_log(p))

    def test_starburst_keys_without_url_are_accepted(self):
        secret = "starburst-lab-secret-6621"
        p = self.project("memory", MODEL, profile_overrides={
            "starburst_client_id": "lab-client",
            "starburst_secret_key": secret,
            "starburst_metadata_failure_strategy": "continue_on_error",
            "starburst_max_column_batch_size": 100,
        })
        result = p.dbt("debug")
        self.assertIn("All checks passed", result.output)
        self.assertNotIn(secret, result.output)
        self.assertNotIn(secret, dbt_log(p))

    def test_role_points_to_roles(self):
        self.assertIn(
            "Trino 'role' is not a dbt-trino profile field; use roles: {system: <role>} or "
            "roles: {<catalog>: <role>}",
            self.debug_output(role="admin"))


if __name__ == "__main__":
    unittest.main()
